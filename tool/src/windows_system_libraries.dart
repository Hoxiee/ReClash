bool isWindowsSystemLibrary(String name) =>
    windowsSystemLibraries.contains(name) ||
    name.startsWith('api-ms-win-') && name.endsWith('.dll') ||
    name.startsWith('ext-ms-win-') && name.endsWith('.dll');
