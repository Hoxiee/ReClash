import 'dart:io';

List<String> checkGeneratedContracts(Directory root) {
  const dartDirectory = 'plugins/rust_api/lib/src/rust';
  const dartPath = '$dartDirectory/frb_generated.dart';
  const rustPath = 'plugins/rust_api/rust/src/frb_generated.rs';
  const paths = [
    dartPath,
    '$dartDirectory/frb_generated.io.dart',
    '$dartDirectory/frb_generated.web.dart',
    rustPath,
  ];
  final failures = <String>[];
  final sources = <String, String>{};
  for (final path in paths) {
    final file = File.fromUri(root.uri.resolve(path));
    if (!file.existsSync()) {
      failures.add('Missing generated file: $path');
    } else {
      sources[path] = file.readAsStringSync();
    }
  }
  for (final entry in sources.entries.where((e) => e.key.endsWith('.dart'))) {
    for (final match in RegExp(
      r"(?:import|export)\s+'([^']+)'",
    ).allMatches(entry.value)) {
      final imported = match[1]!;
      if (Uri.parse(imported).hasScheme) continue;
      final uri = root.uri.resolve(entry.key).resolve(imported);
      if (!File.fromUri(uri).existsSync()) {
        failures.add('Missing generated sibling: $imported (${entry.key})');
      }
    }
  }
  final hashes = <String, String>{};
  for (final entry in {
    dartPath: RegExp(r'rustContentHash\s*=>\s*(-?\d+)\s*;'),
    rustPath: RegExp(
      r'FLUTTER_RUST_BRIDGE_CODEGEN_CONTENT_HASH\s*:\s*i32\s*=\s*(-?\d+)\s*;',
    ),
  }.entries) {
    final source = sources[entry.key];
    if (source == null) continue;
    final match = entry.value.firstMatch(source);
    if (match == null) {
      failures.add('Missing FRB content hash: ${entry.key}');
    } else {
      hashes[entry.key] = match[1]!;
    }
  }
  if (hashes.values.toSet().length > 1) {
    failures.add('FRB content hash mismatch: $hashes');
  }
  final versions = <String, String>{};
  final versionPatterns = [
    RegExp(
      r'@generated by `flutter_rust_bridge`@\s*([^\s.]+(?:\.[^\s.]+)*?)\.(?:\s|$)',
    ),
    RegExp(r'''codegenVersion\s*=>\s*['"]([^'"]+)['"]'''),
    RegExp(r'FLUTTER_RUST_BRIDGE_CODEGEN_VERSION\s*:\s*&str\s*=\s*"([^"]+)"'),
  ];
  for (final entry in sources.entries) {
    for (var i = 0; i < versionPatterns.length; i++) {
      final match = versionPatterns[i].firstMatch(entry.value);
      if (match != null) versions['${entry.key}#$i'] = match[1]!;
    }
  }
  if (versions.values.toSet().length > 1) {
    failures.add('FRB generator version mismatch: $versions');
  }
  return failures;
}

void main(List<String> args) {
  if (args.length > 1) {
    stderr.writeln(
      'Usage: dart run tool/check_generated_contracts.dart [repository-root]',
    );
    exitCode = 64;
    return;
  }
  try {
    final failures = checkGeneratedContracts(
      Directory(args.isEmpty ? '.' : args.single).absolute,
    );
    if (failures.isEmpty) {
      stdout.writeln('FRB generated contracts are consistent.');
    } else {
      stderr.writeln(failures.join('\n'));
      exitCode = 1;
    }
  } on FileSystemException catch (error) {
    stderr.writeln('Could not inspect generated contracts: $error');
    exitCode = 1;
  }
}
