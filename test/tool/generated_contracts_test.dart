import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

import '../../tool/check_generated_contracts.dart';

void main() {
  late Directory root;
  const dartPath = 'plugins/rust_api/lib/src/rust/frb_generated.dart';
  const rustPath = 'plugins/rust_api/rust/src/frb_generated.rs';

  void write(String path, String source) {
    final file = File('${root.path}/$path');
    file.parent.createSync(recursive: true);
    file.writeAsStringSync(source);
  }

  setUp(() {
    root = Directory.systemTemp.createTempSync('generated-contracts-');
    write(
      dartPath,
      'int get rustContentHash => -123;\n'
      "String get codegenVersion => '2.13.0';\n"
      "import 'frb_generated.io.dart'\n"
      "if (dart.library.js_interop) 'frb_generated.web.dart';\n"
      "import 'api/example.dart';\n"
      'void sse_encode_one() {}\nvoid sse_encode_two() {}',
    );
    write(
      rustPath,
      'const FLUTTER_RUST_BRIDGE_CODEGEN_CONTENT_HASH: i32 = -123;\n'
      'const FLUTTER_RUST_BRIDGE_CODEGEN_VERSION: &str = "2.13.0";\n'
      'fn sse_encode_one() {}',
    );
    for (final suffix in ['io', 'web']) {
      write(
        'plugins/rust_api/lib/src/rust/frb_generated.$suffix.dart',
        '// @generated by `flutter_rust_bridge`@ 2.13.0.\n',
      );
    }
    write('plugins/rust_api/lib/src/rust/api/example.dart', '');
  });
  tearDown(() => root.deleteSync(recursive: true));

  test('matching hashes pass despite different codec method counts', () {
    expect(checkGeneratedContracts(root), isEmpty);
  });

  test('hash mismatch fails with both values and paths', () {
    write(
      rustPath,
      'const FLUTTER_RUST_BRIDGE_CODEGEN_CONTENT_HASH: i32 = 456;',
    );
    expect(
      checkGeneratedContracts(root).single,
      allOf(
        contains('hash mismatch'),
        contains('-123'),
        contains('456'),
        contains(rustPath),
      ),
    );
  });

  test('missing hash fails instead of treating absent values as equal', () {
    write(dartPath, '');
    expect(
      checkGeneratedContracts(root),
      contains(contains('Missing FRB content hash')),
    );
  });

  test('missing platform output fails', () {
    File(
      '${root.path}/plugins/rust_api/lib/src/rust/frb_generated.web.dart',
    ).deleteSync();
    expect(
      checkGeneratedContracts(root),
      contains(contains('Missing generated file')),
    );
  });

  test('missing imported API sibling fails', () {
    File(
      '${root.path}/plugins/rust_api/lib/src/rust/api/example.dart',
    ).deleteSync();
    expect(
      checkGeneratedContracts(root),
      contains(contains('Missing generated sibling: api/example.dart')),
    );
  });

  test('generator versions are checked across runtime and header metadata', () {
    write(
      'plugins/rust_api/lib/src/rust/frb_generated.web.dart',
      '// @generated by `flutter_rust_bridge`@ 2.12.0.\n',
    );
    expect(
      checkGeneratedContracts(root),
      contains(contains('generator version mismatch')),
    );
  });

  test('optional generator metadata may be absent', () {
    write(dartPath, 'int get rustContentHash => -123;');
    write(
      rustPath,
      'const FLUTTER_RUST_BRIDGE_CODEGEN_CONTENT_HASH: i32 = -123;',
    );
    expect(checkGeneratedContracts(root), isEmpty);
  });

  test('CLI reports missing files with nonzero exit status', () async {
    File('${root.path}/$rustPath').deleteSync();
    final result = await Process.run('dart', [
      'run',
      'tool/check_generated_contracts.dart',
      root.path,
    ]);
    expect(result.exitCode, 1);
    expect(result.stderr, contains('Missing generated file: $rustPath'));
  });

  test('inspection does not modify generated files', () {
    final before = {
      for (final file in root.listSync(recursive: true).whereType<File>())
        file.path: file.readAsBytesSync(),
    };
    checkGeneratedContracts(root);
    for (final entry in before.entries) {
      expect(File(entry.key).readAsBytesSync(), entry.value);
    }
  });
}
